// Kod 5.2 — Atama ve artırma operatörleri
// Aritmetik ve Atama Operatörleri

int sayac = 10;

sayac += 5;    // 15
sayac -= 3;    // 12
sayac *= 2;    // 24
sayac /= 4;    // 6
sayac %= 4;    // 2

int i = 5;
Console.WriteLine(i++);   // 5 yazar, sonra 6 olur  (son ek)
Console.WriteLine(++i);   // 7 olur, sonra 7 yazar  (ön ek)
