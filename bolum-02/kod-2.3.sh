# Kod 2.3 — En sık kullanacağınız komutlar
# dotnet CLI ile İlk Tanışma

dotnet new list           # kullanılabilir proje şablonları
dotnet new console        # yeni konsol projesi
dotnet restore            # bağımlılıkları indir
dotnet build              # derle
dotnet run                # derle ve çalıştır
dotnet test               # testleri çalıştır
dotnet watch run          # değişiklikte otomatik yeniden çalıştır
dotnet format             # kodu biçim kurallarına göre düzelt
